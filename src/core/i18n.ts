let activeLocale: Locale = "zh-CN";

/** 解析语言设置：auto 时跟随浏览器，中文浏览器用中文，其余用英文。 */
export function resolveLocale(
  language: Language | undefined,
  browserLanguage = typeof navigator === "undefined" ? "zh-CN" : navigator.language,
): Locale {
  if (language === "zh-CN" || language === "en") return language;
  return /^zh/i.test(browserLanguage) ? "zh-CN" : "en";
}

/** 应用语言设置并记录当前语言；返回解析后的 locale。 */
export function applyLanguage(language: Language | undefined): Locale {
  activeLocale = resolveLocale(language);
  return activeLocale;
}

export function setLocale(locale: Locale): void {
  activeLocale = locale;
}

export function getLocale(): Locale {
  return activeLocale;
}

/** 取文案；vars 里的 {name} 占位符会被替换。 */
export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const table = activeLocale === "en" ? EN : ZH;
  const template = table[key] ?? ZH[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

export function hasMessage(key: string): key is MessageKey {
  return key in ZH;
}
